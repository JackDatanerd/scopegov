#!/usr/bin/env node
// Regenerates lib/search/unaccent-map.ts from the database's own unaccent().
//
// Why this exists: lib/search/query.ts must fold the user's query EXACTLY the way the generated
// search_text columns (migrations 062 / 073 / 111) were folded, or a query and its own stored text
// stop matching. The previous hand-written normaliser (NFD + strip U+0300–036F + 8 letters) diverged
// from unaccent() in two directions — see the header of unaccent-map.ts. The table below is
// unaccent() itself, per code point, so there is nothing left to drift.
//
// Usage (any Postgres with the unaccent extension; re-run after a Postgres major upgrade):
//
//   psql -d postgres -At -F $'\t' -c "
//     select cp, encode(convert_to(unaccent(chr(cp)),'UTF8'),'hex')
//     from generate_series(128, 1114111) cp
//     where cp not between 55296 and 57343 and unaccent(chr(cp)) <> chr(cp)" > unaccent_map.tsv
//   node scripts/gen-unaccent-map.mjs unaccent_map.tsv

import fs from 'node:fs'

const src = process.argv[2]
if (!src) { console.error('usage: node scripts/gen-unaccent-map.mjs <unaccent_map.tsv>'); process.exit(1) }

const rows = fs.readFileSync(src, 'utf8').split('\n').filter(Boolean).map(line => {
  const [cp, hex] = line.split('\t')
  return [Number(cp), Buffer.from(hex ?? '', 'hex').toString('utf8')]
})
if (rows.length < 1000 || rows.some(([cp]) => !Number.isInteger(cp))) {
  console.error(`suspicious input (${rows.length} rows) — refusing to write`); process.exit(1)
}

const lit = s => JSON.stringify(s).replace(/[^\x20-\x7e]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'))
const entries = rows.map(([cp, v]) => `0x${cp.toString(16)}:${lit(v)}`)
const lines = []
for (let i = 0; i < entries.length; i += 6) lines.push('  ' + entries.slice(i, i + 6).join(', ') + ',')

fs.writeFileSync(new URL('../lib/search/unaccent-map.ts', import.meta.url), `// GENERATED by scripts/gen-unaccent-map.mjs — do not edit by hand.
//
// Postgres unaccent() applied to every Unicode code point it changes (${rows.length} of them,
// generated from PostgreSQL 16's unaccent.rules). Keys are code points, values are what unaccent()
// returns for that single character ('' for combining marks, so they simply disappear).
//
// This replaces a hand-written NFD normaliser that disagreed with the database in both directions:
//   • it did NOT fold what unaccent() folds beyond accents — curly apostrophes (O’Brien is stored as
//     o'brien), en/em dashes, curly quotes, …, ligatures, the dotless ı, ĳ/ŋ/ħ, fullwidth forms — so a
//     query containing them could never match the stored text;
//   • it DID decompose characters unaccent() leaves alone — every precomposed Hangul syllable and
//     Japanese kana with a dakuten (が, ぱ …) — so those names, stored intact, could never be found.

export const UNACCENT: Readonly<Record<number, string>> = {
${lines.join('\n')}
}
`)
console.log(`wrote lib/search/unaccent-map.ts (${rows.length} entries)`)
